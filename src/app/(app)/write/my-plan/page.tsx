import { createClient } from '@/lib/supabase/server';
import { redirect } from 'next/navigation';
import Link from 'next/link';
import type { Metadata } from 'next';

export const dynamic = 'force-dynamic';

export const metadata: Metadata = { title: 'My Writing Plan — Liravo' };

interface DailyTask {
  day: string;
  task: string;
  goal: string;
}

interface WritingPlan {
  id: string;
  week_start_date: string;
  tasks: DailyTask[];
  generated_at: string;
}

function getWeekStart(): string {
  const now = new Date();
  const day = now.getDay(); // 0 = Sunday
  const diff = now.getDate() - day;
  const weekStart = new Date(now.setDate(diff));
  return weekStart.toISOString().split('T')[0];
}

export default async function MyWritingPlanPage() {
  const supabase = createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) redirect('/login');

  const { data: profile } = await supabase
    .from('users')
    .select('user_types')
    .eq('id', user.id)
    .single();

  const isPremium = profile?.user_types?.includes('creator') ?? false;

  if (!isPremium) {
    return (
      <div className="max-w-2xl mx-auto px-4 py-6">
        <div className="flex items-center justify-between mb-6">
          <h1 className="font-display text-2xl font-bold">My Writing Plan</h1>
          <Link href="/write" className="text-sm text-muted-foreground hover:text-foreground">
            ← Write Hub
          </Link>
        </div>
        <div className="rounded-2xl bg-amber-50 dark:bg-amber-950/30 border border-amber-200 dark:border-amber-800 p-8 text-center">
          <p className="text-4xl mb-4">✨</p>
          <h2 className="font-display text-xl font-bold text-amber-900 dark:text-amber-100 mb-2">
            AI Writing Plans — Premium Feature
          </h2>
          <p className="text-amber-800 dark:text-amber-200 text-sm mb-6">
            Get a personalised weekly writing plan generated by AI based on your genre interests
            and past challenges. Upgrade to premium to unlock.
          </p>
          <Link
            href="/settings/account"
            className="inline-flex items-center gap-2 rounded-lg bg-amber-600 hover:bg-amber-700 text-white text-sm font-medium px-5 py-2.5 transition-colors"
          >
            Upgrade to Premium
          </Link>
        </div>
      </div>
    );
  }

  const weekStart = getWeekStart();

  const { data: plan } = await supabase
    .from('writing_plans')
    .select('*')
    .eq('user_id', user.id)
    .eq('week_start_date', weekStart)
    .maybeSingle();

  return (
    <div className="max-w-2xl mx-auto px-4 py-6">
      <div className="flex items-center justify-between mb-6">
        <div>
          <h1 className="font-display text-2xl font-bold">My Writing Plan</h1>
          <p className="text-muted-foreground text-sm mt-0.5">
            Week of {new Date(weekStart).toLocaleDateString('en-US', { month: 'long', day: 'numeric' })}
          </p>
        </div>
        <Link href="/write" className="text-sm text-muted-foreground hover:text-foreground">
          ← Write Hub
        </Link>
      </div>

      {!plan ? (
        <div className="rounded-xl border bg-muted p-8 text-center">
          <p className="text-muted-foreground mb-2">No plan generated for this week yet.</p>
          <p className="text-xs text-muted-foreground">
            AI plans are generated automatically each Monday. Check back soon!
          </p>
        </div>
      ) : (
        <div className="space-y-4">
          {((plan as WritingPlan).tasks ?? []).map((task: DailyTask, i: number) => (
            <div key={i} className="rounded-xl border bg-card p-5">
              <div className="flex items-center gap-2 mb-2">
                <span className="text-xs font-medium bg-amber-100 dark:bg-amber-900 text-amber-800 dark:text-amber-200 px-2 py-0.5 rounded-full">
                  {task.day}
                </span>
              </div>
              <p className="font-medium text-sm">{task.task}</p>
              {task.goal && (
                <p className="text-xs text-muted-foreground mt-1">Goal: {task.goal}</p>
              )}
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
